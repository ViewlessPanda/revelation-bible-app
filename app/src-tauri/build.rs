// The parser for the committed expected-hash file lives in the shared crate
// (crates/revelation-content, std-only with default features off), where it is
// unit-tested; the pipeline's T16 tests use the same parser.
use revelation_content::hashfile;
use std::path::PathBuf;

/// The committed expected SHA-256 values (pipeline/DESIGN.md 10.2). The app
/// compiles them in; it never reads a hash from beside a content file.
const EXPECTED_FILE: &str = "../../pipeline/tests/expected/output-sha256.txt";

fn compile_in_expected_hashes() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let path = manifest.join(EXPECTED_FILE);
    println!("cargo:rerun-if-changed={}", path.display());
    let text = std::fs::read_to_string(&path).unwrap_or_else(|e| {
        panic!(
            "cannot read the expected content hashes at {}: {e}",
            path.display()
        )
    });
    let entries =
        hashfile::parse(&text).unwrap_or_else(|e| panic!("malformed {}: {e}", path.display()));
    let kjv = hashfile::lookup(&entries, "kjv.sqlite")
        .unwrap_or_else(|e| panic!("{}: {e}", path.display()));
    let lex = hashfile::lookup(&entries, "content.sqlite")
        .unwrap_or_else(|e| panic!("{}: {e}", path.display()));
    let search = hashfile::lookup(&entries, "kjv-search.sqlite")
        .unwrap_or_else(|e| panic!("{}: {e}", path.display()));
    let mhcc = hashfile::lookup(&entries, "mhcc.sqlite")
        .unwrap_or_else(|e| panic!("{}: {e}", path.display()));
    let mut out = String::from(
        "// GENERATED by build.rs from pipeline/tests/expected/output-sha256.txt. Do not edit.\n",
    );
    out.push_str(&format!(
        "/// Expected SHA-256 of `kjv.sqlite`.\npub const KJV_SQLITE: &str = \"{kjv}\";\n"
    ));
    out.push_str(&format!(
        "/// Expected SHA-256 of `content.sqlite` (the lexicons).\npub const CONTENT_SQLITE: &str = \"{lex}\";\n"
    ));
    out.push_str(&format!(
        "/// Expected SHA-256 of `kjv-search.sqlite` (the phrase-search index).\npub const KJV_SEARCH_SQLITE: &str = \"{search}\";\n"
    ));
    out.push_str(&format!(
        "/// Expected SHA-256 of `mhcc.sqlite` (the commentary).
pub const MHCC_SQLITE: &str = \"{mhcc}\";
"
    ));
    out.push_str("/// Every `(file, sha256)` pair in the expected-hash file.\n#[allow(dead_code)]\npub const ALL: &[(&str, &str)] = &[\n");
    for (f, h) in &entries {
        out.push_str(&format!("    (\"{f}\", \"{h}\"),\n"));
    }
    out.push_str("];\n");
    let dest = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR")).join("expected_sha256.rs");
    std::fs::write(dest, out).expect("write expected_sha256.rs");
}

fn main() {
    compile_in_expected_hashes();
    // App commands get generated `allow-<command>` permissions; only the ones
    // granted in capabilities/main.json can be invoked from the WebView.
    tauri_build::try_build(tauri_build::Attributes::new().app_manifest(
        tauri_build::AppManifest::new().commands(&[
            "app_info",
            "list_books",
            "get_chapter",
            "get_strongs",
            "get_highlights",
            "set_highlight",
            "load_state",
            "save_state",
            "start_new_user_data",
            "search",
            "bookmarks_list",
            "bookmark_set",
            "bookmark_clear",
            "bookmark_restore",
            "get_commentary",
            "marks_for_chapter",
            "pen_apply",
            "pen_erase",
            "mark_remove",
            "mark_recolor",
            "marks_replace_chapter",
            "notes_list",
            "note_save",
            "app_close",
        ]),
    ))
    .expect("failed to run tauri-build");
}
