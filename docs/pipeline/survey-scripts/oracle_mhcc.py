"""Independent oracle files for the MHCC commentary (DESIGN.md 11.1 and 17).

Usage:
  py -I -B oracle_mhcc.py <mhcc.osis.xml> <CMT-MHCC-CW20.sha256> <out_dir>

Writes <out_dir>/mhcc-blocks.tsv and <out_dir>/mhcc-anchors.tsv, and nothing
else. Run from outside sources/raw, with paths as arguments. Shares no code
with the Rust pipeline (no XML parser at all: the regex tokenizer and
allowlist walker of mhcc_osis.py). Fail-closed: the source is read once and
checked against its checksum file (osis_tokens.load_pinned), the whole file
passes the strict reader before anything is computed, the pinned totals
below must hold, and both files are written only after every step passed.

mhcc-blocks.tsv, one line per block (<p>, <title> or <table> inside a book,
document order):
  ord, book, chapter ('-' before the book's first chapter milestone),
  anchor ('-' outside every verse anchor), element name, attributes
  ('name=value' joined with ';', '-' for none), raw_bytes / raw_sha256 (the
  block's source bytes from '<' of its start tag to '>' of its end tag),
  text_bytes / text_sha256 (those bytes with every tag removed and '&amp;'
  replaced by '&').
mhcc-anchors.tsv, one line per <verse sID/> ... <verse eID/> pair:
  ord, sID, first_block, last_block, number of verses, osisID exactly as
  written (space-separated).
"""
import hashlib
import os
import platform
import sys

sys.dont_write_bytecode = True
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from osis_tokens import Refused, load_pinned, read_checksum_file  # noqa: E402
import mhcc_osis  # noqa: E402

FACTS = {"blocks": 16255, "anchors": 4297, "verse_refs": 28968, "chapters": 1189}


def sha(b):
    return hashlib.sha256(b).hexdigest()


def file_sha(path):
    with open(path, "rb") as f:
        return sha(f.read())


def main(argv):
    if len(argv) != 4:
        sys.exit(__doc__)
    src, sums, out = argv[1], argv[2], argv[3]
    data = load_pinned(src, sums)
    doc = mhcc_osis.read(data)
    got = {
        "blocks": len(doc.blocks),
        "anchors": len(doc.anchors),
        "verse_refs": sum(len(a["osisID"].split(" ")) for a in doc.anchors),
        "chapters": doc.chapters,
    }
    if got != FACTS:
        raise Refused("pinned totals differ: %r" % got)

    head = [
        "# generator: docs/pipeline/survey-scripts/oracle_mhcc.py sha256 %s" % file_sha(os.path.abspath(__file__)),
        "# helper: docs/pipeline/survey-scripts/mhcc_osis.py sha256 %s" % file_sha(os.path.join(HERE, "mhcc_osis.py")),
        "# helper: docs/pipeline/survey-scripts/osis_tokens.py sha256 %s" % file_sha(os.path.join(HERE, "osis_tokens.py")),
        "# source: CMT-MHCC-CW20 mhcc.osis.xml sha256 %s" % read_checksum_file(sums, "mhcc.osis.xml"),
        "# python: %s" % platform.python_version(),
        "# Generated by an independent implementation (DESIGN.md 11.1). Never edit by hand;",
        "# regenerate only when a source pin or a generator changes, with the owner's review.",
    ]
    blocks = ["# mhcc-blocks.tsv: one line per block (<p>, <title>, <table> inside a book), document order."] + head + [
        "# columns: ord\tbook\tchapter\tanchor\tname\tattrs\traw_bytes\traw_sha256\ttext_bytes\ttext_sha256",
        "# raw: source bytes of the whole element; text: raw minus every tag, '&amp;' -> '&'",
    ]
    for b in doc.blocks:
        attrs = ";".join("%s=%s" % kv for kv in b["attrs"]) or "-"
        blocks.append("\t".join(str(x) for x in (
            b["ord"], b["book"], "-" if b["chapter"] is None else b["chapter"],
            "-" if b["anchor"] is None else b["anchor"], b["name"], attrs,
            len(b["raw"]), sha(b["raw"]), len(b["text"]), sha(b["text"]))))
    anchors = ["# mhcc-anchors.tsv: one line per verse anchor (<verse sID/> ... <verse eID/>), document order."] + head + [
        "# columns: ord\tsid\tfirst_block\tlast_block\tverses\tosisID (as written)",
    ]
    for a in doc.anchors:
        anchors.append("\t".join(str(x) for x in (
            a["ord"], a["sid"], a["first"], a["last"], len(a["osisID"].split(" ")), a["osisID"])))

    os.makedirs(out, exist_ok=True)
    for name, lines in (("mhcc-blocks.tsv", blocks), ("mhcc-anchors.tsv", anchors)):
        with open(os.path.join(out, name), "wb") as f:
            f.write(("\n".join(lines) + "\n").encode("ascii"))
    print("wrote mhcc-blocks.tsv (%d blocks) and mhcc-anchors.tsv (%d anchors)" % (len(doc.blocks), len(doc.anchors)))


if __name__ == "__main__":
    main(sys.argv)
